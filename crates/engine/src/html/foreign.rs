//! WHATWG HTML 13.2.6.5 foreign-content name/attribute adjustments. These are
//! standard data tables, not an imported parser implementation.
use super::tokenizer::Tag;
use crate::dom::{AttributeNamespace, Namespace};

pub(super) fn adjust(tag: &Tag, namespace: Namespace) -> Tag {
    let name = if namespace == Namespace::Svg {
        svg_name(&tag.name)
    } else {
        &tag.name
    };
    let attrs = tag
        .attrs
        .iter()
        .map(|(name, value)| {
            let name = match namespace {
                Namespace::Svg => svg_attribute(name),
                Namespace::MathMl if name == "definitionurl" => "definitionURL",
                _ => name,
            };
            (name.into(), value.clone())
        })
        .collect();
    Tag {
        name: name.into(),
        attrs,
        merge_attribute_order: Vec::new(),
        self_closing: tag.self_closing,
    }
}

pub(super) fn attribute_namespace(name: &str) -> Option<AttributeNamespace> {
    match name {
        "xlink:actuate" | "xlink:arcrole" | "xlink:href" | "xlink:role" | "xlink:show"
        | "xlink:title" | "xlink:type" => Some(AttributeNamespace::XLink),
        "xml:lang" | "xml:space" => Some(AttributeNamespace::Xml),
        "xmlns" | "xmlns:xlink" => Some(AttributeNamespace::Xmlns),
        _ => None,
    }
}

pub(super) fn breakout(tag: &Tag) -> bool {
    matches!(
        tag.name.as_str(),
        "b" | "big"
            | "blockquote"
            | "body"
            | "br"
            | "center"
            | "code"
            | "dd"
            | "div"
            | "dl"
            | "dt"
            | "em"
            | "embed"
            | "h1"
            | "h2"
            | "h3"
            | "h4"
            | "h5"
            | "h6"
            | "head"
            | "hr"
            | "i"
            | "img"
            | "li"
            | "listing"
            | "menu"
            | "meta"
            | "nobr"
            | "ol"
            | "p"
            | "pre"
            | "ruby"
            | "s"
            | "small"
            | "span"
            | "strong"
            | "strike"
            | "sub"
            | "sup"
            | "table"
            | "tt"
            | "u"
            | "ul"
            | "var"
    ) || tag.name == "font"
        && ["color", "face", "size"]
            .iter()
            .any(|&a| tag.attrs.contains_key(a))
}

