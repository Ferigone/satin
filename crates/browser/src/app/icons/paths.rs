macro_rules! glyphs {
    ($($name:ident => [$($element:expr),+ $(,)?]),+ $(,)?) => {
        #[allow(dead_code)] // Some artwork is consumed only when its UI is wired.
        #[derive(Clone, Copy, Debug, PartialEq, Eq)]
        pub(crate) enum Glyph {
            $($name),+
        }

        impl Glyph {
            pub(super) fn shape(self) -> &'static Shape {
                match self {
                    $(Self::$name => {
                        static SHAPE: OnceLock<Shape> = OnceLock::new();
                        SHAPE.get_or_init(|| Shape::new(&[$($element),+]))
                    }),+
                }
            }
        }

        #[cfg(test)]
        pub(super) const ALL: &[Glyph] = &[$(Glyph::$name),+];
    };
}

