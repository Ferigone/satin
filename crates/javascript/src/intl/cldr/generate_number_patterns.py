"""Generate the symbol, digit and compact-pattern tables from Unicode CLDR 49.

Usage: python generate_number_patterns.py cldr-numbers-full-49.0.0.tgz cldr-core-49.0.0.tgz
The second argument may also be the unpacked cldr-core directory.
"""
import json
from pathlib import Path
import sys
import tarfile
import zlib

VERSION = "49.0.0"
OUT = Path(__file__).parent

def read_core(path):
    if path.is_dir():
        assert json.loads((path/"package.json").read_text())["version"] == VERSION
        return json.loads((path/"supplemental/numberingSystems.json").read_text())
    with tarfile.open(path) as archive:
        assert json.load(archive.extractfile("package/package.json"))["version"] == VERSION
        return json.load(archive.extractfile("package/supplemental/numberingSystems.json"))

def records(numbers):
    # Store common Latin patterns once; alternate numbering systems override
    # individual values, as specified by this locale's CLDR data.
    base = {}
    for system in sorted((s[21:] for s in numbers if s.startswith("symbols-numberSystem-")), key=lambda s:(s != "latn",s)):
        values = numbers["symbols-numberSystem-"+system]
        fields = {k:values[k] for k in ("nan","infinity","exponential","minusSign") if k in values}
        formats = numbers.get("decimalFormats-numberSystem-"+system, {})
        for width in ("long", "short"):
            for key, pattern in formats.get(width,{}).get("decimalFormat",{}).items():
                mag, plural = key.split("-count-",1)
                if mag.isdigit() and "-alt-" not in plural:
                    fields[f"{width}.{len(mag)-1:02}.{plural}"] = pattern
        if system == "latn":
            base = fields
            yield from fields.items()
        else:
            for key,value in fields.items():
                if base.get(key) != value:
                    yield f"{system}:{key}",value

def main(numbers, core):
    buffer = bytearray()
    pool = {}
    locales = {}
    with tarfile.open(numbers) as archive:
        assert json.load(archive.extractfile("package/package.json"))["version"] == VERSION
        for member in sorted(archive.getnames()):
            if not member.endswith("/numbers.json"):
                continue
            tag, source = next(iter(json.load(archive.extractfile(member))["main"].items()))
            fields = sorted(records(source["numbers"]))
            for k,v in fields:
                assert not any(c in k+v for c in "\t\r\n")
            data = "".join(k+"\t"+v+"\n" for k,v in fields).encode()
            if data not in pool:
                start = len(buffer)
                buffer.extend(zlib.compress(data,9))
                pool[data] = (start,len(buffer))
            locales[tag] = pool[data]
    (OUT/"number-patterns.bin").write_bytes(buffer)
    digits=read_core(core)["supplemental"]["numberingSystems"]
    with (OUT/"number_patterns.rs").open("w") as out:
        print("// Generated by generate_number_patterns.py from CLDR 49.0.0.",file=out)
        blocks = sorted(set(locales.values()))
        print("pub(super) const BLOCKS: &[(usize, usize)] = &[",file=out)
        for start,end in blocks: print(f"    ({start}, {end}),",file=out)
        print("];\npub(super) const LOCALES: &[(&str, usize)] = &[", file=out)
        for tag,span in sorted(locales.items()): print(f'    ("{tag}", {blocks.index(span)}),', file=out)
        print("];\npub(super) const DIGITS: &[(&str, &str)] = &[",file=out)
        for system,record in sorted(digits.items()):
            if record["_type"] == "numeric": print(f'    ("{system}", "{record["_digits"]}"),',file=out)
        print("];",file=out)

if __name__ == "__main__":
    main(Path(sys.argv[1]),Path(sys.argv[2]))
