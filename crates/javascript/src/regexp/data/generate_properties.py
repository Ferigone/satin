"""Build Unicode 17 sets and exact aliases for ECMAScript property escapes.

Inputs (pass their directory as argv[1]):
  https://www.unicode.org/Public/17.0.0/ucd/PropertyAliases.txt
  https://www.unicode.org/Public/17.0.0/ucd/PropertyValueAliases.txt
  https://registry.npmjs.org/regenerate-unicode-properties/-/regenerate-unicode-properties-10.2.2.tgz
Save the npm archive as regenerate-properties.tgz. Its MIT license is included
beside the generated data. The UCD is covered by LICENSE.txt.
"""
from collections import defaultdict
from hashlib import sha256
from io import BytesIO
from pathlib import Path
import re
import sys
import tarfile

DIGESTS = {
    "regenerate-properties.tgz": "b16f7dae33d26d9b80587fca0609b1920dc6a76e4dd413afed39142ec3805e58",
    "PropertyAliases.txt": "4441f573caf952ffece1d7c892e7715bd7136dfc26f96eb6f268bf1e474715fb",
    "PropertyValueAliases.txt": "64e9a5f76f7a1e8b5a47d6a1f9a26522a251208f5276bdfa1559dac7cf2e827a",
}
GROUPS = {
    "Binary_Property": "BINARY",
    "General_Category": "CATEGORIES",
    "Script": "SCRIPTS",
    "Script_Extensions": "SCRIPT_EXTENSIONS",
}


def read_ranges(source):
    lines = source.splitlines()
    first = re.fullmatch(r"const set = require\('regenerate'\)\((.*?)\);", lines[0])
    if not first or lines[-1] != "exports.characters = set;":
        raise ValueError("Unknown regenerate module format")
    ranges = [(int(n, 16), int(n, 16)) for n in first[1].split(", ") if n]
    pattern = re.compile(r"\.addRange\((0x[0-9A-F]+), (0x[0-9A-F]+)\)")
    for line in filter(None, lines[1:-1]):
        if pattern.sub("", line) != "set;":
            raise ValueError(f"Unknown range syntax: {line[:70]}")
        ranges.extend((int(a, 16), int(b, 16)) for a, b in pattern.findall(line))
    merged = []
    for start, end in sorted(ranges):
        if merged and start <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], end))
        else:
            merged.append((start, end))
    return b"".join(n.to_bytes(3, "big") for span in merged for n in span)


def aliases(data):
    for line in data.decode().splitlines():
        row = line.partition("#")[0].strip()
        if row:
            yield [item.strip() for item in row.split(";")]


def main(directory):
    source = {name: (directory / name).read_bytes() for name in DIGESTS}
    for name, expected in DIGESTS.items():
        if sha256(source[name]).hexdigest() != expected:
            raise ValueError(f"Unexpected hash for {name}")
    tables = defaultdict(dict)
    ranges = bytearray()
    offsets = {}
    here = Path(__file__).parent
    with tarfile.open(fileobj=BytesIO(source["regenerate-properties.tgz"])) as archive:
        for member in sorted(archive.getmembers(), key=lambda m: m.name):
            path = Path(member.name)
            group = path.parent.name
            if path.suffix != ".js" or group not in GROUPS:
                continue
            points = read_ranges(archive.extractfile(member).read().decode())
            if points not in offsets:
                offsets[points] = (len(ranges), len(points)//6)
                ranges.extend(points)
            tables[group][path.stem] = offsets[points]
        license = archive.extractfile("package/LICENSE-MIT.txt").read()
        (here / "LICENSE-regenerate-properties.txt").write_bytes(license)
    for row in aliases(source["PropertyAliases.txt"]):
        if row[1] in tables["Binary_Property"]:
            for name in row:
                tables["Binary_Property"][name] = tables["Binary_Property"][row[1]]
    for prop, *names in aliases(source["PropertyValueAliases.txt"]):
        groups = {"gc": ["General_Category"], "sc": ["Script", "Script_Extensions"]}.get(prop, [])
        for group in groups:
            if names[1] in tables[group]:
                for name in names:
                    tables[group][name] = tables[group][names[1]]
    rs = ["// Generated by generate_properties.py from Unicode 17.0.0."]
    for group, name in GROUPS.items():
        rs.append(f"pub(super) const {name}: &[(&str, usize, usize)] = &[")
        for alias, (offset, count) in sorted(tables[group].items()):
            rs.append(f'    ("{alias}", {offset}, {count}),')
        rs.append("];")
    (here / "property-index.rs").write_text("\n".join(rs)+"\n")
    (here / "property-ranges.bin").write_bytes(ranges)


if __name__ == "__main__":
    main(Path(sys.argv[1]))
