# The binary properties implemented by the matcher.
BINARY_MATCHING = {
    "ASCII_Hex_Digit": "AsciiHexDigit",
    "Hex_Digit": "HexDigit",
    "Soft_Dotted": "SoftDotted",
}

def fields(source, name):
    data = (source / name).read_bytes()
    if sha256(data).hexdigest() != SOURCES[name]:
        raise ValueError(f"{name} does not match the pinned Unicode 17.0.0 data")
    for line in data.decode("utf-8").splitlines():
        body = line.partition("#")[0].strip()
        if body:
            yield tuple(part.strip() for part in body.split(";"))

def write_case(path, mappings):
    """Map each point to its contiguous equivalence group in a point array."""
    groups = defaultdict(set)
    for point, canonical in mappings.items():
        groups[canonical].add(point)
        groups[canonical].add(canonical)
    index = []
    points = []
    for _, group in sorted(groups.items()):
        index.extend((point, len(points), len(group)) for point in group)
        points.extend(sorted(group))
    index.sort()
    assert len({row[0] for row in index}) == len(index)
    data = struct.pack("<I", len(index))
    for point, offset, count in index:
        data += struct.pack("<IHH", point, offset, count)
    data += struct.pack(f"<{len(points)}I", *points)
    path.write_bytes(data)

def write_property_aliases(source, path):
    tables = {"gc": set(), "sc": set()}
    for name, *aliases in fields(source, "PropertyValueAliases.txt"):
        if name in tables:
            tables[name].update(aliases)
    out = ["// Unicode 17.0.0 alias tables generated by data/generate.py.\n"]
    for name, aliases in [
        ("BINARY", BINARY_PROPERTY_ALIASES.split()),
        ("CATEGORIES", tables["gc"]),
        ("SCRIPTS", tables["sc"]),
    ]:
        out.append(f"const {name}: &[&str] = &[\n")
        out.extend(f'    "{alias}",\n' for alias in sorted(aliases))
        out.append("];\n")
    path.write_bytes("".join(out).encode("ascii"))

def write_property_ranges(source, path):
    ranges = {name: [] for name in BINARY_MATCHING}
    for extent, name, *_ in fields(source, "PropList.txt"):
        if name in ranges:
            first, sep, last = extent.partition("..")
            ranges[name].append((int(first, 16), int(last if sep else first, 16)))
    out = ["// Unicode 17.0.0 property ranges generated by data/generate.py.\n"]
    for name, points in ranges.items():
        points.sort()
        assert points and all(a[1] < b[0] for a, b in zip(points, points[1:]))
        out.append(f"const {name.upper()}: &[(u32, u32)] = &[\n")
        out.extend(f"    (0x{first:X}, 0x{last:X}),\n" for first, last in points)
        out.append("];\n")
    aliases = {
        alias: BINARY_MATCHING[name]
        for name, *other in map(str.split, BINARY_PROPERTY_ALIASES.strip().splitlines())
        if name in BINARY_MATCHING
        for alias in [name, *other]
    }
    out.append("const MATCHED_BINARY: &[(&str, Property)] = &[\n")
    out.extend(f'    ("{alias}", Property::{kind}),\n' for alias, kind in sorted(aliases.items()))
    out.append("];\n")
    path.write_bytes("".join(out).encode("ascii"))

def main(source, out):
    folding = {}
    for point, kind, replacement, *_ in fields(source, "CaseFolding.txt"):
        if kind in ("C", "S"):
            folding[int(point, 16)] = int(replacement, 16)
    write_case(out / "case-fold.bin", folding)
    uppercase = {
        int(row[0], 16): int(row[12], 16) for row in fields(source, "UnicodeData.txt") if row[12]
    }
    for point, _, _, upper, condition, *_ in fields(source, "SpecialCasing.txt"):
        if not condition:
            uppercase[int(point, 16)] = int(upper, 16) if " " not in upper else int(point, 16)
    legacy = {
        point: upper for point, upper in uppercase.items()
        if point <= 0xFFFF and upper <= 0xFFFF and point != upper
        and not (point >= 128 and upper < 128)
    }
    write_case(out / "legacy-case.bin", legacy)
    for prop, filename in (("ID_Start", "id-start.bin"), ("ID_Continue", "id-continue.bin")):
        data = bytearray()
        for extent, name, *_ in fields(source, "DerivedCoreProperties.txt"):
            if name != prop:
                continue
            first, sep, last = extent.partition("..")
            data.extend(struct.pack("<II", int(first, 16), int(last if sep else first, 16)))
        (out / filename).write_bytes(data)
    write_property_aliases(source, out / "property-aliases.rs")
    write_property_ranges(source, out / "property-ranges.rs")

if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(__file__).parent)
